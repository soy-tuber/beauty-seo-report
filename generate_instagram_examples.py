def build_posts():
    posts = []
    for t in T:
        for i, angle in enumerate(ANGLES):
            typ, angle_name, cta, time_hint, title, lines = angle(t)
            # ハッシュタグ: 検索タグ3-4 + コミュニティタグ1-2 = 5個前後(実データ中央値5)
            stags = t["stags"][:4] if i % 2 == 0 else t["stags"][:3]
            ctags = [t["ctags"][i % len(t["ctags"])], t["ctags"][(i + 2) % len(t["ctags"])]]
            tags = stags + ctags
            posts.append(dict(theme=t["label"], key=t["key"], gap=t["gap"], kw=t["kw"],
                              typ=typ, angle=angle_name, cta=cta, time=time_hint,
                              title=title, cap="\n".join(lines), tags=tags))
    return posts

